defmodule MagSked.CourtsTest do
  use MagSked.DataCase
  alias MagSked.Courts
  doctest MagSked.Courts

  test "avail_to_lookup/1" do
    court_avail = %{
      1 => %{
        "2026-08-16" => [
          ["15:00", "15:30", "16:00"],
          ["18:00", "18:30", "19:00", "19:30"]
        ],
        "2026-08-18" => [
          ["15:30", "16:00"]
        ],
        "2026-08-19" => [
          ["13:00", "13:30"],
          ["15:00", "15:30", "16:00"]
        ]
      },
      2 => %{
        "2026-08-16" => [
          ["14:30", "15:00", "15:30", "16:00", "16:30"],
          ["18:00", "18:30", "19:00", "19:30"]
        ],
        "2026-08-17" => [["13:00", "13:30", "14:00"], ["15:30", "16:00", "16:30"]],
        "2026-08-18" => [
          ["13:00", "13:30"]
        ]
      }
    }

    assert Courts.avail_lookup_map(court_avail) == %{
             "2026-08-16" => [
               [
                 {"14:30", %{2 => true}},
                 {"15:00", %{2 => true, 1 => true}},
                 {"15:30", %{2 => true, 1 => true}},
                 {"16:00", %{2 => true, 1 => true}},
                 {"16:30", %{2 => true}}
               ],
               [
                 {"18:00", %{2 => true, 1 => true}},
                 {"18:30", %{2 => true, 1 => true}},
                 {"19:00", %{2 => true, 1 => true}},
                 {"19:30", %{2 => true, 1 => true}}
               ]
             ],
             "2026-08-17" => [
               [
                 {"13:00", %{2 => true}},
                 {"13:30", %{2 => true}},
                 {"14:00", %{2 => true}}
               ],
               [
                 {"15:30", %{2 => true}},
                 {"16:00", %{2 => true}},
                 {"16:30", %{2 => true}}
               ]
             ],
             "2026-08-18" => [
               [
                 {"13:00", %{2 => true}},
                 {"13:30", %{2 => true}}
               ],
               [
                 {"15:30", %{1 => true}},
                 {"16:00", %{1 => true}}
               ]
             ],
             "2026-08-19" => [
               [
                 {"13:00", %{1 => true}},
                 {"13:30", %{1 => true}}
               ],
               [
                 {"15:00", %{1 => true}},
                 {"15:30", %{1 => true}},
                 {"16:00", %{1 => true}}
               ]
             ]
           }
  end
end
